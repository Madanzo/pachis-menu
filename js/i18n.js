let currentLanguage = 'en';

export function setLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('pachisLanguage', lang);
    applyTranslations();
}

export function getLanguage() {
    return currentLanguage;
}

export function t(key) {
    const keys = key.split('.');
    let value = translations[currentLanguage];

    for (const k of keys) {
        if (value && value[k] !== undefined) {
            value = value[k];
        } else {
            // Fallback to English
            value = translations.en;
            for (const k2 of keys) {
                if (value && value[k2] !== undefined) {
                    value = value[k2];
                } else {
                    return key; // Return key if not found
                }
            }
            break;
        }
    }

    return value;
}

export function initLanguage() {
    const savedLang = localStorage.getItem('pachisLanguage');
    if (savedLang) {
        currentLanguage = savedLang;
    }

    // Also check verification data for country
    const verificationDataStr = localStorage.getItem('pachisVerificationData');
    if (verificationDataStr) {
        try {
            const data = JSON.parse(verificationDataStr);
            if (data.country) {
                const country = data.country.toLowerCase().trim();
                if (country === 'mexico' || country === 'méxico' || country === 'mx') {
                    currentLanguage = 'es';
                }
            }
        } catch (e) {
            console.error('Error reading language from verification data:', e);
        }
    }
}

export function applyTranslations() {
    // Update HTML lang attribute
    document.documentElement.lang = currentLanguage === 'es' ? 'es' : 'en';

    // Age Verification Modal
    const ageTitle = document.querySelector('.age-verification-header h2');
    const ageSubtitle = document.querySelector('.age-verification-header p');
    if (ageTitle) ageTitle.textContent = t('ageVerificationTitle');
    if (ageSubtitle) ageSubtitle.textContent = t('ageVerificationSubtitle');

    // Form labels - Age Verification
    updateLabel('firstName', t('firstName'));
    updateLabel('lastName', t('lastName'));
    updateLabel('email', t('email'));
    updateLabel('phone', t('phone'));
    updateLabel('streetAddress', t('streetAddress'));
    updateLabel('city', t('city'));
    updateLabel('state', t('state'));
    updateLabel('zipCode', t('zipCode'));
    updateLabel('country', t('country'));

    // Age question
    const ageQuestionLabel = document.querySelector('.age-verification-form .form-group label[style*="font-size: 1rem"]');
    if (ageQuestionLabel) ageQuestionLabel.textContent = t('ageQuestion');

    // Age radio options
    const ageYesLabel = document.querySelector('#age-yes + span');
    const ageNoLabel = document.querySelector('#age-no + span');
    if (ageYesLabel) ageYesLabel.textContent = t('ageYes');
    if (ageNoLabel) ageNoLabel.textContent = t('ageNo');

    // Submit button
    const verifyBtn = document.querySelector('.verification-submit');
    if (verifyBtn) verifyBtn.textContent = t('verifyEnter');

    // Disclaimer
    const disclaimer = document.querySelector('.age-disclaimer');
    if (disclaimer) disclaimer.textContent = t('ageDisclaimer');

    // Settings form labels
    updateLabel('settingsFirstName', t('firstName'));
    updateLabel('settingsLastName', t('lastName'));
    updateLabel('settingsEmail', t('email'));
    updateLabel('settingsPhone', t('phone'));
    updateLabel('settingsStreetAddress', t('streetAddress'));
    updateLabel('settingsCity', t('city'));
    updateLabel('settingsState', t('state'));
    updateLabel('settingsZipCode', t('zipCode'));
    updateLabel('settingsCountry', t('country'));

    // Settings save button
    const saveBtn = document.querySelector('#settings-form .btn-telegram');
    if (saveBtn) saveBtn.innerHTML = t('saveChanges');

    // Settings modal title
    const settingsTitle = document.querySelector('#settings-modal .cart-modal-header h2');
    if (settingsTitle) settingsTitle.textContent = t('profileTitle');

    // Navigation labels
    const homeLabel = document.querySelector('.nav-button:nth-child(1) .nav-label');
    const cartLabel = document.querySelector('.nav-button:nth-child(2) .nav-label');
    const profileLabel = document.querySelector('.nav-button:nth-child(3) .nav-label');
    if (homeLabel) homeLabel.textContent = t('home');
    if (cartLabel) cartLabel.textContent = t('cart');
    if (profileLabel) profileLabel.textContent = t('profile');

    // Cart modal
    const cartTitle = document.querySelector('#cart-modal .cart-modal-header h2');
    if (cartTitle) cartTitle.textContent = t('yourCart');

    const clearBtn = document.querySelector('.btn-clear');
    if (clearBtn && clearBtn.getAttribute('onclick') === 'clearCart()') {
        clearBtn.textContent = t('clearCart');
    }

    const telegramBtn = document.querySelector('.btn-telegram[onclick="sendToTelegram()"]');
    if (telegramBtn) telegramBtn.innerHTML = t('sendToTelegram');

    // Order success modal
    const successTitle = document.querySelector('.order-success-title');
    const successMessage = document.querySelector('.order-success-message');
    const connectBtn = document.querySelector('.order-success-btn');
    const continueBtn = document.querySelector('.order-success-close');

    if (successTitle) successTitle.textContent = t('orderSuccessTitle');
    if (successMessage) successMessage.textContent = t('orderSuccessMessage');
    if (connectBtn) connectBtn.innerHTML = t('connectOnTelegram');
    if (continueBtn) continueBtn.textContent = t('continueShopping');

    // Promo banner (bundle)
    const promoTitle = document.querySelector('#promo-banner .promo-title');
    if (promoTitle) promoTitle.textContent = t('bundleAndSave');

    // Wholesale banner
    const wholesaleTitle = document.querySelector('#wholesale-banner .promo-title');
    const wholesaleBtn = document.querySelector('#wholesale-banner .wholesale-btn');
    if (wholesaleTitle) wholesaleTitle.textContent = t('wholesaleAvailable');
    if (wholesaleBtn) wholesaleBtn.textContent = t('wholesaleMessage');

    // Category tabs
    document.querySelectorAll('.tab-button').forEach(btn => {
        const category = btn.getAttribute('data-category');
        if (category && t('categories')[category]) {
            btn.textContent = t('categories')[category];
        }
    });
}

function updateLabel(inputId, text) {
    const input = document.getElementById(inputId);
    if (input) {
        const label = document.querySelector(`label[for="${inputId}"]`);
        if (label) label.textContent = text;
    }
}
